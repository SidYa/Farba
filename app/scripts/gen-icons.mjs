// Generates ui/src/lib/icons.generated.ts from Material Symbols (outlined, weight 500: one
// weight for every icon in the app, owner decision 2026-10-14; it was 700).
// Add an icon name to ICONS and run `pnpm icons`. The SVGs are embedded so the app does not
// depend on node_modules paths at runtime (Vite's import.meta.glob skips node_modules).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const ICONS = [
  "add", "arrow_downward", "arrow_upward", "brightness_auto", "brush", "check", "chevron_right",
  "cancel", "clear_all", "close", "close_small", "colorize", "content_copy", "content_cut", "content_paste",
  "contrast", "crop", "crop_square", "dark_mode", "delete", "deselect", "edit", "exposure",
  "file_open", "filter_none", "filter_vintage", "fit_screen", "flip", "format_color_fill", "gradient", "image", "instant_mix", "ink_eraser",
  "invert_colors", "lasso_select", "light_mode", "link", "link_off", "lock", "lock_open", "menu",
  "merge", "more_vert", "aspect_ratio", "photo_size_select_large", "rotate_left", "open_in_full",
  "3d_rotation", "transform", "settings", "more_horiz", "extension", "background_replace", "filter_b_and_w",
  "palette", "healing", "grain", "deblur", "center_focus_strong", "blur_on", "vignette", "format_bold", "format_italic",
  "format_underlined", "strikethrough_s", "vertical_align_center", "format_letter_spacing",
  "format_clear",
  "note_add", "open_with", "redo", "remove", "rotate_right", "save", "save_as", "select", "swap_vert",
  "text_fields", "tune", "undo", "visibility", "visibility_off", "zoom_in",
  "zoom_out", "approval", "pan_tool_alt", "water_drop", "tonality", "info", "favorite", "format_color_reset", "border_outer",
  "alt_route", "cached", "view_apps", "preview", "wand_shine", "ink_selection",
];

const require = createRequire(import.meta.url);
const root = join(dirname(require.resolve("@material-symbols/svg-500/package.json")), "outlined");

/** Icons made from another one by a transform (same stroke weight): name -> [base, transform]. */
const DERIVED = {
  flip_vertical: ["flip", "rotate(90 480 -480)"],
};

const load = (name) =>
  readFileSync(join(root, `${name}.svg`), "utf8")
    .trim()
    .replace(/ width="48" height="48"/, "");

const entries = [
  ...ICONS.map((name) => [name, load(name)]),
  ...Object.entries(DERIVED).map(([name, [base, transform]]) => [
    name,
    load(base).replace(/(<svg[^>]*>)([\s\S]*)(<\/svg>)/, `$1<g transform="${transform}">$2</g>$3`),
  ]),
].map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`);

const out = `// Generated by scripts/gen-icons.mjs (\`pnpm icons\`). Do not edit.
// Material Symbols Outlined, weight 500 - Apache-2.0, https://github.com/google/material-design-icons
export const MATERIAL_ICONS: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync(new URL("../ui/src/lib/icons.generated.ts", import.meta.url), out);
console.log(`icons.generated.ts: ${ICONS.length} icons`);
